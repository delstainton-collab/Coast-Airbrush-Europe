// Helper lookup functions
export function getBrandById(id) {
  if (!id) return null;
  const target = id.toLowerCase();
  return BRANDS_MASTER.find(b => b.id === target || b.slug === target);
}

export function getBrandByName(name) {
  if (!name) return null;
  const n = name.toLowerCase();
  return BRANDS_MASTER.find(b => 
    b.name.toLowerCase().includes(n) || 
    n.includes(b.slug) || 
    b.slug.replace("-", " ").includes(n) ||
    (b.filterBrand && n.includes(b.filterBrand.toLowerCase()))
  );
}

export function getAllBrands() {
  return BRANDS_MASTER;
}
